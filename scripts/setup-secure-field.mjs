#!/usr/bin/env node
/**
 * SiteSurveyor — secure-field encryption-key setup.
 * --------------------------------------------------
 * Run:  node scripts/setup-secure-field.mjs
 *
 * What it does:
 *   1. Generates a random 32-byte AES-GCM key, base64-encoded.
 *   2. Writes it to backend/supabase/.env.local (git-ignored) for local dev.
 *   3. Prints the key and the exact `supabase secrets set` command for prod.
 *   4. Offers to run `supabase secrets set` for you if the CLI is available.
 *
 * Security: keep the key out of source control and chat tools. Back it up in
 * a password manager or vault. If you lose it, existing encrypted Crypto Wallet
 * payment-method data cannot be decrypted.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const BACKEND_DIR = path.join(ROOT, 'backend');
const SUPABASE_DIR = path.join(BACKEND_DIR, 'supabase');
const ENV_FILE = path.join(SUPABASE_DIR, '.env.local');
const ENV_KEY = 'SECURE_FIELD_ENCRYPTION_KEY';

function c(code, s) {
  return `\x1b[${code}m${s}\x1b[0m`;
}
const bold = (s) => c('1', s);
const green = (s) => c('32', s);
const yellow = (s) => c('33', s);
const red = (s) => c('31', s);
const cyan = (s) => c('36', s);

function generateKey() {
  return crypto.randomBytes(32).toString('base64');
}

function readExistingKey() {
  if (!fs.existsSync(ENV_FILE)) return null;
  const txt = fs.readFileSync(ENV_FILE, 'utf8');
  const m = txt.match(new RegExp(`^${ENV_KEY}=(.+)$`, 'm'));
  return m ? m[1].trim() : null;
}

function writeLocalEnv(key) {
  const comment =
    '# SiteSurveyor secure-field Edge Function encryption key\n' +
    '# Generated by scripts/setup-secure-field.mjs.\n' +
    '# Keep this secret out of source control.\n';

  let content = comment;
  if (fs.existsSync(ENV_FILE)) {
    const existing = fs.readFileSync(ENV_FILE, 'utf8');
    // Replace existing key line or append fresh.
    const cleaned = existing
      .split('\n')
      .filter((line) => !line.startsWith(`${ENV_KEY}=`) && !line.startsWith('# secure-field'))
      .join('\n');
    content = cleaned.trim() + `\n${ENV_KEY}=${key}\n`;
  } else {
    content += `${ENV_KEY}=${key}\n`;
  }

  fs.mkdirSync(path.dirname(ENV_FILE), { recursive: true });
  fs.writeFileSync(ENV_FILE, content, { mode: 0o600 });
}

function ask(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) => rl.question(question, (a) => { rl.close(); resolve(a.trim()); }));
}

function supabaseCliAvailable() {
  const probe = spawnSync('npx', ['supabase', '--version'], {
    cwd: BACKEND_DIR, encoding: 'utf8', shell: process.platform === 'win32',
  });
  return probe.status === 0;
}

async function main() {
  console.log(bold('\n  SiteSurveyor secure-field encryption-key setup\n'));

  const key = generateKey();
  writeLocalEnv(key);

  console.log(green('  ✓ Key written to ') + cyan(ENV_FILE));
  console.log('    (used automatically when serving Edge Functions locally)\n');

  console.log(bold('  ENCRYPTION KEY (base64, 32 bytes):'));
  console.log('    ' + red(key) + '\n');

  const secretCmd = `npx supabase secrets set ${ENV_KEY}=${key}`;

  if (supabaseCliAvailable()) {
    const a = await ask('  Set this key in your linked Supabase project now? [y/N] ');
    if (a.toLowerCase() === 'y' || a.toLowerCase() === 'yes') {
      const res = spawnSync('npx', ['supabase', 'secrets', 'set', `${ENV_KEY}=${key}`], {
        cwd: BACKEND_DIR, stdio: 'inherit', shell: process.platform === 'win32',
      });
      if (res.status === 0) {
        console.log(green('\n  ✓ Key set as a Supabase secret.\n'));
      } else {
        console.log(yellow('\n  Could not set the secret automatically. Run it manually from the backend directory:\n'));
        console.log('    cd backend');
        console.log('    ' + secretCmd + '\n');
      }
    } else {
      console.log('\n  Set it yourself later (run from backend/):');
      console.log('    cd backend');
      console.log('    ' + secretCmd + '\n');
    }
  } else {
    console.log('  Set the key as a Supabase secret (run from backend/):');
    console.log('    cd backend');
    console.log('    ' + secretCmd + '\n');
    console.log('  Make sure you have the Supabase CLI installed and are linked to your project:\n');
    console.log('    npx supabase login');
    console.log('    npx supabase link --project-ref <your-project-ref>\n');
  }

  console.log(bold('  Remaining steps:'));
  console.log('    1. Back up this key in a password manager. Losing it means encrypted');
  console.log('       Crypto Wallet payment-method data cannot be recovered.');
  console.log('    2. Deploy the Edge Function (run from backend/):');
  console.log('         cd backend');
  console.log('         npx supabase functions deploy secure-field\n');
}

main().catch((e) => {
  console.error(red('\n  Setup failed: ') + (e?.message || e) + '\n');
  process.exit(1);
});
